export async function downloadPortfolioZip(files, addToast) {
  try {
    let JSZip;
    try {
      const mod = await import("jszip");
      JSZip = mod.default || mod;
    } catch (e) {
      addToast &&
        addToast(
          "JSZip is not installed. Run `npm install jszip` and rebuild.",
          "error"
        );
      return;
    }

    const zip = new JSZip();

    // Add each file from the files object
    if (files && typeof files === "object") {
      Object.entries(files).forEach(([filename, content]) => {
        zip.file(filename, content);
      });
    }

    // Add README.md with setup instructions
    const readme = `# Your Portfolio

## Running locally

\`\`\`bash
npm install
npm run dev
\`\`\`

Or open index.html directly in your browser for a static preview.

## File structure

This portfolio was generated by PersonaForge. The source files are included
so you can customize them to your liking.

## Deploying

You can deploy this portfolio to any static hosting service:
- Vercel: \`vercel deploy\`
- Netlify: drag and drop this folder
- GitHub Pages: push to a gh-pages branch
`;

    zip.file("README.md", readme);

    const blob = await zip.generateAsync({ type: "blob" });

    // Trigger download via a temporary anchor
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "portfolio.zip";
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    setTimeout(() => URL.revokeObjectURL(url), 10000);

    addToast && addToast("Portfolio downloaded successfully!", "success");
  } catch (err) {
    console.error("Download failed:", err);
    addToast && addToast("Download failed. Please try again.", "error");
  }
}